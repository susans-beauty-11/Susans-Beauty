    "    const processCjBatch = async (cjProducts, _fromBeautySource = false, sourceLabel = '') => {",
    '      if (!Array.isArray(cjProducts) || cjProducts.length === 0) return 0;',
    '      let batchSaved = 0;',
    '      const bulkOps = [];',
    '      const syncTimestamp = new Date();',
    '',
    '      for (const item of cjProducts) {',
