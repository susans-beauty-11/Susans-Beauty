    '          { lastSyncedAt: { $lt: staleCutoff } },',
    '          { lastSyncedAt: null },',
    '          { lastSyncedAt: { $exists: false } }',
    '        ]',
    '      })',
    "        .select('_id')",
    '        .lean();',
    '',
    '      if (staleDocs.length > 0) {',
