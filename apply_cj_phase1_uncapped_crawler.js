    '        const dedupeSkuKey = `sku:${baseSku.toLowerCase()}`;',
    '        const dedupeTitleKey = `title:${normTitleKey || rawTitle.toLowerCase()}`;',
    '',
    '        if (',
    '          (dedupePidKey && seenKeys.has(dedupePidKey)) ||',
