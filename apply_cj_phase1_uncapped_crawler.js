    '                return {',
    '                  sku: v.vid || v.variantSku || baseSku,',
    "                  variantName: v.variantEn || v.variantName || v.variantKey || 'Standard Option',",
    '                  wholesalePriceUsd: Number(variantRawPrice.toFixed(2)),',
    '                  price: computedVariantRetail,',
    '                  imageUrl: v.variantImage || img',
    '                };',
    '              })',
    '            : [',
    '                {',
    '                  sku: item.vid || baseSku,',
    "                  variantName: 'Standard',",
    '                  wholesalePriceUsd: Number(rawBasePrice.toFixed(2)),',
    '                  price: Number(((rawBasePrice * activeMarkup) + shippingAddonUsd + labelAddonUsd).toFixed(2)),',
    '                  imageUrl: img',
    '                }',
    '              ];',
    '',
    '        const primaryRetailPrice = Number(',
    '          mappedVariants[0]?.price ||',
    '            ((rawBasePrice * activeMarkup) + shippingAddonUsd + labelAddonUsd).toFixed(2)',
    '        );',
    '        const blueprintLabels = classifyProductForBlueprint(effectiveTitle, category, rawDesc);',
    "        const cleanedCopy = typeof extractAndCleanProductDescription === 'function'",
    '          ? extractAndCleanProductDescription({',
    '              title: effectiveTitle,',
    '              description: existingProd?.customTitleLocked ? existingProd.description : rawDesc,',
    "              seoAnswerCapsule: existingProd?.seoAnswerCapsule || '',",
    '              rawCjData: { description: rawDesc },',
    '              ritualStep: blueprintLabels.ritualStep,',
    '              skinTypes: blueprintLabels.skinTypes,',
    '              skinConcerns: blueprintLabels.skinConcerns,',
    '              keyActives: blueprintLabels.keyActives',
    '            })',
    '          : {',
    "              description: String(rawDesc || '').replace(/<[^>]*>?/gm, ' ').replace(/\\s+/g, ' ').trim(),",
    "              seoAnswerCapsule: existingProd?.seoAnswerCapsule || ''",
    '            };',
    '',
    '        const updatePayload = {',
    '          title: effectiveTitle,',
    "          cjPid: cjPid || existingProd?.cjPid || '',",
    "          cjSku: baseSku || existingProd?.cjSku || '',",
    '          normalizedTitleKey: effectiveNormTitle,',
    '          customTitleLocked: Boolean(existingProd?.customTitleLocked),',
    '          lastSyncedAt: syncTimestamp,',
    '          description: cleanedCopy.description,',
    '          seoAnswerCapsule: cleanedCopy.seoAnswerCapsule,',
    '          imageUrl: img,',
    '          price: primaryRetailPrice,',
    '          wholesalePriceUsd: Number(rawBasePrice.toFixed(2)),',
    '          markupMultiplier: activeMarkup,',
    '          estimatedWeightGrams: weightGrams,',
    "          originCountryCode: 'CN',",
    '          selectedLogisticName: activeLogistic,',
    '          shippingCostUsd: Number(activeShippingCost.toFixed(2)),',
    '          shippingIncludedInPrice: activeShippingIncluded,',
    '          availableLogistics:',
    '            Array.isArray(existingProd?.availableLogistics) && existingProd.availableLogistics.length > 0',
    '              ? existingProd.availableLogistics',
    '              : fallbackLogistics,',
    '          customLabelConfig: activeCustomLabel,',
    '          tags: blueprintLabels.tags,',
    '          skinTypes: blueprintLabels.skinTypes,',
    '          skinConcerns: blueprintLabels.skinConcerns,',
    '          sensitivitySafe: blueprintLabels.sensitivitySafe,',
    '          sensitivityLabel: blueprintLabels.sensitivityLabel,',
    '          ritualStep: blueprintLabels.ritualStep,',
    '          keyActives: blueprintLabels.keyActives,',
    '          variants: mappedVariants,',
    '          rawCjData: { ...item, categoryName: category || item.categoryName }',
    '        };',
    '',
    '        if (existingProd?._id) {',
    '          bulkOps.push({',
    '            updateOne: {',
    '              filter: { _id: existingProd._id },',
    '              update: { $set: updatePayload }',
    '            }',
    '          });',
    '          updatedProductsCount++;',
    '        } else {',
    '          const upsertFilter = cjPid ? { cjPid } : { normalizedTitleKey: effectiveNormTitle };',
    '          bulkOps.push({',
    '            updateOne: {',
    '              filter: upsertFilter,',
    '              update: { $set: updatePayload },',
    '              upsert: true',
    '            }',
    '          });',
    '          indexExistingProduct(updatePayload);',
    '          newProductsAdded++;',
    '        }',
    '',
    '        if (dedupePidKey) seenKeys.add(dedupePidKey);',
    '        seenKeys.add(dedupeSkuKey);',
    '        seenKeys.add(dedupeTitleKey);',
    '        totalProcessed++;',
    '        batchSaved++;',
    '      }',
    '',
    '      if (bulkOps.length > 0) {',
    '        await Product.bulkWrite(bulkOps, { ordered: false });',
    '      }',
    '',
    '      return batchSaved;',
    '    };',
    '',
    '    // Resilient single-page fetcher with exponential backoff for HTTP 429 and CJ 1600200 QPS limits',
    '    const fetchCjProductPage = async (url, maxRetries = 3) => {',
    '      for (let attempt = 1; attempt <= maxRetries; attempt++) {',
    '        try {',
    '          const response = await axios.get(url, { headers, timeout: 20000 });',
    '          const cjCode = Number(response.data?.code || 200);',
    "          const cjMsg = String(response.data?.message || '');",
    '          if ((cjCode === 1600200 || /too many requests|qps/i.test(cjMsg)) && attempt < maxRetries) {',
    '            console.warn(`⏳ CJ QPS limit hit (attempt ${attempt}/${maxRetries}), backing off...`);',
    '            await delay(1800 * attempt);',
    '            continue;',
    '          }',
    '          const dataBlock = response.data?.data || {};',
    '          const list = Array.isArray(dataBlock.list)',
    '            ? dataBlock.list',
    '            : Array.isArray(dataBlock.content)',
    '            ? dataBlock.content',
    '            : [];',
    '          const total = Number(dataBlock.total || dataBlock.totalRecords || 0);',
    '          return { ok: true, list, total };',
    '        } catch (err) {',
    '          const status = err?.response?.status;',
    '          if ((status === 429 || status >= 500 || err.code === \'ECONNABORTED\') && attempt < maxRetries) {',
    '            console.warn(`⏳ CJ HTTP ${status || err.code} on attempt ${attempt}/${maxRetries}, backing off...`);',
    '            await delay(2000 * attempt);',
    '            continue;',
    '          }',
    '          return { ok: false, list: [], total: 0, error: err?.response?.data?.message || err.message };',
    '        }',
    '      }',
    "      return { ok: false, list: [], total: 0, error: 'Max retries exceeded' };",
    '    };',
